"""Rebuild research/cafe/districts.yaml from the cached Seoul 상권 sales file (no network).

    python -m sim.cafe.build_districts [--raw data/raw/seoul] [--quarter 20262]

THSMON_SELNG_AMT / _CO are QUARTER totals despite the 당월 name (research §1.1), so per-month = ÷3 and
per-day = ÷91. Store counts (VwsmTrdarStorQq 2026Q2) come from research/cafe/params.yaml because only
3120012 is cached locally; the research file pulled all three live on 2026-10-13.

The `seoul` block is the Seoul-wide mean sales per cafe for the same quarter, the denominator of the demand index
(상권 per-store ÷ Seoul per-store): every 상권's CS100010 sales over its 유사업종 점포 count, only 상권 that have both a
sales row and stores. It needs the whole quarter's store file (VwsmTrdarStorQq/{quarter}.csv.gz, fetched with
pipelines.common.seoul_all; Seoul OpenAPI key).
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from .params import DISTRICTS_YAML, ROOT, load_params

BANDS = [("00_06", 6), ("06_11", 5), ("11_14", 3), ("14_17", 3), ("17_21", 4), ("21_24", 3)]
SRC = "서울시 상권분석서비스 VwsmTrdarSelngQq {q} CS100010 (data/raw/seoul cache), research §1.3"


def build(raw: Path, quarter: str) -> dict:
    import pandas as pd

    p = load_params()
    df = pd.read_csv(raw / "VwsmTrdarSelngQq" / f"{quarter}.csv.gz")
    df = df[df.SVC_INDUTY_CD == "CS100010"].set_index("TRDAR_CD")
    out = {}
    for code, meta in p["district_meta"].items():
        r = df.loc[int(code)]
        stores = meta["stores"]["value"]
        amt, co = float(r.THSMON_SELNG_AMT), float(r.THSMON_SELNG_CO)
        per_hour = {b: float(r[f"TMZON_{b}_SELNG_CO"]) / co / h for b, h in BANDS}
        peak_band = max(per_hour, key=per_hour.get)
        avg_day = co / 91
        wkend_day = float(r.WKEND_SELNG_CO) / 26
        wkday_day = float(r.MDWK_SELNG_CO) / 65
        src = SRC.format(q=quarter)
        out[code] = {
            "trdar_name": str(r.TRDAR_CD_NM),
            "sales_per_store_month_krw": {"value": round(amt / 3 / stores), "grade": "H", "source": src,
                                          "note": "분기 합계 ÷ 3 ÷ 점포 수 (프랜차이즈 포함 평균)"},
            "tx_per_store_day": {"value": round(co / stores / 91, 2), "grade": "H", "source": src,
                                 "note": "분기 거래건수 ÷ 점포 수 ÷ 91일"},
            "ticket_krw": {"value": round(amt / co), "grade": "H", "source": src},
            "peak_hour_tx_share": {"value": round(per_hour[peak_band], 4), "grade": "H", "source": src,
                                   "note": f"피크 시간대 {peak_band.replace('_', '~')}시 거래 비중 ÷ 시간 수"},
            "peak_band": peak_band.replace("_", "~"),
            "band_tx_share": {"value": {b.replace("_", "~"): round(float(r[f"TMZON_{b}_SELNG_CO"]) / co, 4) for b, _ in BANDS},
                              "grade": "H", "source": src, "note": "시간대별 거래 비중 (00~06, 06~11, 11~14, 14~17, 17~21, 21~24)"},
            "weekend_day_factor": {"value": round(wkend_day / avg_day, 3), "grade": "H", "source": src,
                                   "note": "주말 거래건수 ÷ 26일 ÷ 전체 일평균"},
            "weekday_day_factor": {"value": round(wkday_day / avg_day, 3), "grade": "H", "source": src,
                                   "note": "주중 거래건수 ÷ 65일 ÷ 전체 일평균"},
        }
    stores = pd.read_csv(raw / "VwsmTrdarStorQq" / f"{quarter}.csv.gz")
    stores = stores[stores.SVC_INDUTY_CD == "CS100010"][["TRDAR_CD", "SIMILR_INDUTY_STOR_CO"]]
    m = df.reset_index().merge(stores, on="TRDAR_CD")
    m = m[m.SIMILR_INDUTY_STOR_CO > 0]
    n = float(m.SIMILR_INDUTY_STOR_CO.sum())
    seoul = {
        "sales_per_store_month_krw": {"value": round(float(m.THSMON_SELNG_AMT.sum()) / 3 / n), "grade": "H",
                                      "source": f"{SRC.format(q=quarter)} + VwsmTrdarStorQq {quarter} (서울 전체)",
                                      "note": f"분기 합계 ÷ 3 ÷ 점포 수, 매출과 점포가 둘 다 있는 상권 {len(m)}곳, 점포 {round(n):,}곳 (프랜차이즈 포함)"},
        "tx_per_store_day": {"value": round(float(m.THSMON_SELNG_CO.sum()) / n / 91, 2), "grade": "H",
                             "source": f"{SRC.format(q=quarter)} + VwsmTrdarStorQq {quarter} (서울 전체)"},
    }
    return {"quarter": quarter, "seoul": seoul, "districts": out}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", type=Path, default=ROOT / "data" / "raw" / "seoul")
    ap.add_argument("--quarter", default="20262")
    a = ap.parse_args()
    data = build(a.raw, a.quarter)
    header = "# GENERATED by `python -m sim.cafe.build_districts` from the cached Seoul 상권 file. Do not hand-edit.\n"
    DISTRICTS_YAML.write_text(header + yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8")
    print(f"wrote {DISTRICTS_YAML}")


if __name__ == "__main__":
    main()
